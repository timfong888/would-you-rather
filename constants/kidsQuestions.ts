/**
 * Question bank for the kids-audience categories (youngest age under 13): Tiny Choices, Make-Believe, Giggle Factory,
 * Road Trip Rally, Dinner Table, Heart to Heart, Future Me and Holiday Table (docs/specs/kids-family-categories.md §2.2).
 *
 * Written for children and the adults playing with them: no romance, no violence, no brands, nothing scary,
 * nothing that singles out a body or a family situation. Ids are `kf-N` and never change (votes and share links key
 * on them). Each category lists its 8 free starters first, then its paid questions (volume 2), so index-based
 * gating works. Questions written for an SEO landing page carry that page's tag (constants/seoPages.ts); new
 * questions carry none. Teen questions (Real Talk, ages 13–17) are in teenQuestions.ts with `tn-` ids.
 *
 * Questions carry no vote counts: real counts come from the votes table (docs/specs).
 *
 * Keep api/_lib/data.js in sync (npm run verify:data checks it).
 */
import type { CategoryId, Question } from './questions';

const kf = (n: number, category: CategoryId, tag: string | null, optionA: string, optionB: string, volume?: number): Question => ({
  id: `kf-${n}`,
  category,
  ...(volume ? { volume } : {}),
  optionA,
  optionB,
  ...(tag ? { tags: [tag] } : {}),
});
/** One of the category's 8 free starters. */
const free = (n: number, category: CategoryId, tag: string | null, optionA: string, optionB: string) => kf(n, category, tag, optionA, optionB);
/** Behind the category unlock (volume 2). */
const paid = (n: number, category: CategoryId, tag: string | null, optionA: string, optionB: string) => kf(n, category, tag, optionA, optionB, 2);

